
from app.incident_service import analyze_incident
from app.rescue_engine import find_compatible_providers
from app.ai_service import generate_rescue_explanation


def orchestrate_rescue(
    product_type: str,
    quantity_kg: float,
    current_temp: float,
    required_temp: float
):
    incident = analyze_incident(
        product_type=product_type,
        quantity_kg=quantity_kg,
        current_temp=current_temp,
        required_temp=required_temp
    )

    if not incident["rescue_required"]:
        return {
            "status": "NO_RESCUE_REQUIRED",
            "incident": incident,
            "decision": {
                "message": "No temperature deviation detected.",
                "reason": "Incident rules do not indicate a rescue requirement."
            },
            "ai_explanation": None,
            "recommendation": None,
            "alternatives": [],
            "human_approval_required": False
        }

    providers = find_compatible_providers(
        product_type=product_type,
        quantity_kg=quantity_kg,
        required_temp=required_temp
    )

    if not providers:
        decision = {
            "message": "No compatible rescue provider found.",
            "reason": (
                "Available providers did not satisfy "
                "the product, capacity and temperature constraints."
            )
        }

        return {
            "status": "NO_COMPATIBLE_PROVIDER",
            "incident": incident,
            "decision": decision,
            "ai_explanation": None,
            "recommendation": None,
            "alternatives": [],
            "human_approval_required": False
        }

    selected = providers[0]
    alternatives = providers[1:]

    decision = {
        "message": "A compatible rescue option has been identified.",
        "reason": (
            f"{selected['name']} satisfies the configured "
            f"compatibility and capacity constraints. "
            f"Its listed service cost is ₹{selected['cost']} "
            f"and its distance is {selected['distance_km']} km."
        ),
        "selection_method": "Lowest listed cost, then shortest distance"
    }

    try:
        ai_explanation = generate_rescue_explanation(
            incident=incident,
            decision=decision,
            provider=selected
        )
        ai_status = "AI_EXPLANATION_GENERATED"

    except Exception as error:
        print(f"OpenAI explanation unavailable: {error}")
        ai_explanation = (
            "AI explanation is temporarily unavailable. "
            "The rescue recommendation was generated by the "
            "deterministic rescue engine."
        )
        ai_status = "AI_UNAVAILABLE"

    return {
        "status": "RESCUE_PLAN_READY",
        "incident": incident,
        "decision": decision,
        "ai_explanation": ai_explanation,
        "ai_status": ai_status,
        "recommendation": selected,
        "alternatives": alternatives,
        "human_approval_required": True,
        "payment_authorized": False
    }
